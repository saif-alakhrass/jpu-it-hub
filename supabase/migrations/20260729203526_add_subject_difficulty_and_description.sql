# Add difficulty and course_description columns to subjects

## Overview
Adds two optional columns to the `subjects` table so course difficulty and a
curated course description can be stored directly on the subject row, instead
of being derived client-side from a hardcoded lookup table.

## Changes
1. New columns on `public.subjects`:
   - `difficulty` (text, nullable) — one of 'سهلة' | 'متوسطة' | 'صعبة'.
     No CHECK constraint is added to keep the column flexible for future
     difficulty levels; the application validates the value.
   - `course_description` (text, nullable) — a curated, admin-editable
     description of the course distinct from the generic `description`
     column (which remains for short subject blurbs).
2. Backfill: populate the new columns from the existing static
   `COURSE_DETAILS` map shipped in the app where an exact name match exists,
   so existing subjects get sensible defaults without manual data entry.
3. Index on `difficulty` to support future filtering by difficulty.

## Security
- No RLS policy changes. The columns inherit the existing public SELECT /
  owner-or-admin write policies already on `subjects`.
- Only authenticated owners/admins can UPDATE these columns (existing policy).

## Notes
- Fully idempotent: uses ADD COLUMN IF NOT EXISTS and ON CONFLICT DO NOTHING
  for the backfill.
- Safe to re-run; existing data is never destroyed.
*/

